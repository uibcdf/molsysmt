def _generated_cache(source, optimization=""):
    entry = PackagePath(cache_from_source(source, optimization=optimization))
    # pip records generated bytecode without the hash/size of an archive member.
    entry.hash = None
    entry.size = None
    return entry


@pytest.mark.parametrize("optimization", ["", "1", "2"])
@pytest.mark.parametrize(
    "source",
    [
        "molsysviewer_molsysmt/__init__.py",
        "molsysviewer_molsysmt/tools.py",
        "molsysviewer_molsysmt/_private/argument/update_view.py",
    ],
)
def test_installed_inventory_accepts_only_source_backed_generated_caches(
    source, optimization
):
    paths = [*TOOLS_FILES, _generated_cache(source, optimization)]
    installed.validate_native_viewer_metadata(_distribution(files=paths))
    # The same cache stays forbidden at the shared source/archive boundary.
    assert any("unreviewed" in error for error in validate_tools_files(paths))


def test_generated_cache_cannot_replace_a_missing_source():
    source = "molsysviewer_molsysmt/tools.py"
    paths = [*sorted(TOOLS_FILES - {source}), _generated_cache(source)]
    with pytest.raises(RuntimeError, match="files are missing"):
        installed.validate_native_viewer_metadata(_distribution(files=paths))


@pytest.mark.parametrize(
    "path",
    [
        "molsysviewer_molsysmt/tools.pyc",
        "molsysviewer_molsysmt/__pycache__/tools.pyc",
        "molsysviewer_molsysmt/__pycache__/tools.foreign-interpreter.pyc",
        "molsysviewer_molsysmt/__pycache__/notes.txt",
        cache_from_source("molsysviewer_molsysmt/runtime.py"),
        cache_from_source("molsysviewer_molsysmt/tools.py", optimization="3"),
        cache_from_source("molsysviewer_molsysmt/_private/runtime.py"),
    ],
)
def test_unreviewed_or_nonstandard_cache_paths_remain_rejected(path):
    entry = PackagePath(path)
    entry.hash = None
    entry.size = None
    with pytest.raises(RuntimeError, match="retired or unreviewed"):
        installed.validate_native_viewer_metadata(
            _distribution(files=[*TOOLS_FILES, entry])
        )


@pytest.mark.parametrize("record_field", ["hash", "size"])
def test_archive_recorded_bytecode_does_not_get_the_generated_cache_exception(
    record_field,
):
    entry = _generated_cache("molsysviewer_molsysmt/tools.py")
    setattr(entry, record_field, "archive metadata")
    with pytest.raises(RuntimeError, match="retired or unreviewed"):
        installed.validate_native_viewer_metadata(
            _distribution(files=[*TOOLS_FILES, entry])
        )


def test_retired_source_and_its_cache_remain_rejected_together():
    retired = "molsysviewer_molsysmt/runtime.py"
    with pytest.raises(RuntimeError, match="retired or unreviewed"):
        installed.validate_native_viewer_metadata(
            _distribution(files=[*TOOLS_FILES, retired, _generated_cache(retired)])
        )


def test_real_pip_install_keeps_the_reviewed_inventory_valid(tmp_path):
    """Reproducing the installer RECORD change without a runtime or network install."""
    wheel = tmp_path / "molsysmt-1.0.0-py3-none-any.whl"
    info = "molsysmt-1.0.0.dist-info"
    contents = {name: b"# Reviewed source fixture.\n" for name in TOOLS_FILES}
    contents.update(
        {
            f"{info}/METADATA": b"Metadata-Version: 2.1\nName: molsysmt\nVersion: 1.0.0\n",
            f"{info}/WHEEL": (
                b"Wheel-Version: 1.0\nRoot-Is-Purelib: true\nTag: py3-none-any\n"
            ),
            f"{info}/entry_points.txt": (
                b"[molsysviewer.addons]\nmolsysmt-tools = molsysviewer_molsysmt.tools\n"
            ),
        }
    )
    record = io.StringIO()
    writer = csv.writer(record)
    writer.writerows((name, "", "") for name in sorted(contents))
    writer.writerow((f"{info}/RECORD", "", ""))
    contents[f"{info}/RECORD"] = record.getvalue().encode()
    with ZipFile(wheel, "w") as archive:
        for name, content in contents.items():
            archive.writestr(name, content)
    assert not any(name.endswith(".pyc") for name in contents)
    target = tmp_path / "installed"
    environment = os.environ.copy()
    environment.pop("PYTHONDONTWRITEBYTECODE", None)
    environment.pop("PYTHONPYCACHEPREFIX", None)
    environment["TMPDIR"] = str(tmp_path)
    subprocess.run(
        [
            sys.executable,
            "-m",
            "pip",
            "--disable-pip-version-check",
            "--no-cache-dir",
            "install",
            "--no-index",
            "--no-deps",
            "--compile",
            "--target",
            str(target),
            str(wheel),
        ],
        check=True,
        capture_output=True,
        text=True,
        env=environment,
    )
    distribution = metadata.Distribution.at(target / info)
    caches = [entry for entry in distribution.files if entry.suffix == ".pyc"]
    assert len(caches) == len(TOOLS_FILES)
    assert all(entry.hash is None and entry.size is None for entry in caches)
    assert all(distribution.locate_file(entry).is_file() for entry in caches)
    installed.validate_native_viewer_metadata(distribution)
