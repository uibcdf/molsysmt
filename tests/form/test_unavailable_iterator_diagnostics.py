@pytest.mark.parametrize("module_name,class_name,method_name,form", ROUTES)
def test_unavailable_iterator_reports_the_form(
    module_name, class_name, method_name, form
):
    module = importlib.import_module(module_name)
    iterator_type = getattr(module, class_name)
    # Isolate the already reviewed unconditional refusal. No engine, file or
    # scientific computation is involved; normalization is not being tested.
    method = inspect.unwrap(getattr(iterator_type, method_name))
    instance = object.__new__(iterator_type)
    with pytest.raises(NotImplementedIteratorError) as caught:
        if method_name == "__init__":
            method(instance, molecular_system=object())
        else:
            method(instance)
    assert form in str(caught.value)
